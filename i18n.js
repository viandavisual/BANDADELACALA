const attrs=new WeakMap(),lastAttrs=new WeakMap();
const exclude=new Set(['SCRIPT','STYLE','NOSCRIPT','CODE','PRE','TEXTAREA','SVG','OPTION-IGNORE']);
const months=['gener','febrer','març','abril','maig','juny','juliol','agost','setembre','octubre','novembre','desembre'];
const weekdays=['dilluns','dimarts','dimecres','dijous','divendres','dissabte','diumenge'];
const locale=()=>lang==='en'?'en-GB':lang==='nl'?'nl-NL':'ca-ES';
function translate(text){
  if(lang==='ca')return text;
  const prefix=text.match(/^\s*/)?.[0]||'';
  const suffix=text.match(/\s*$/)?.[0]||'';
  const core=text.trim();if(!core)return text;
  const dict=DICT[lang];
  let value=dict[core];
  if(value===undefined){
    const normalized=core.replace(/\s+/g,' ').replace(/’/g,"'");
    value=dict[normalized];
    if(value===undefined){
      // Traducció segura de dates, salutacions i recompte dinàmic.
      let result=core;
      const hello=core.match(/^(BENVINGUT\/DA|BENVINGUT|BENVINGUDA|Hola!)\s+(.+)$/i);
      if(hello)result=(lang==='en'?'WELCOME':'WELKOM')+' '+hello[2];
      const pref=core.match(/^(DEMOS PROPER CONCERT:)(.+)$/);
      if(pref)result=dict[pref[1]]+pref[2];
      for(let i=0;i<12;i++){
        const name=months[i];
        const tr=new Intl.DateTimeFormat(locale(),{month:'long'}).format(new Date(2026,i,5));
        result=result.replace(new RegExp('\\b'+name+'\\b','gi'),(match)=>match[0]===match[0].toUpperCase()?tr.toUpperCase():match[0]===match[0].toLocaleUpperCase('ca-ES')[0]?tr[0].toUpperCase()+tr.slice(1):tr);
      }
      for(let i=0;i<7;i++){
        const name=weekdays[i];
        const tr=new Intl.DateTimeFormat(locale(),{weekday:'long'}).format(new Date(2026,10,23+i));
        result=result.replace(new RegExp('\\b'+name+'\\b','gi'),tr);
      }
      result=result.replace(/\b(\d+)\s+Fotos\b/g,(_,n)=>n+' '+dict.Fotos)
        .replace(/\b(\d+)\s+pistes\b/g,(_,n)=>n+' '+dict.pistes)
        .replace(/\b(\d+)\s+Cartells\b/g,(_,n)=>n+' '+dict.Cartells)
        .replace(/\b(\d+)\s+MOSTRES?\b/g,(_,n)=>n+' '+dict[n==='1'?'MOSTRA':'MOSTRES'])
        .replace(/\b(\d+)\s+foto(s)?\b/gi,(_,n,s)=>n+' '+dict[s?'fotos':'foto']);
      // Cap substitució genèrica de noms lliures ni títols de peces.
      value=result;
    }
  }
  return prefix+value+suffix;
}
function nodeOk(n){let parent=n.parentElement;if(!parent || exclude.has(parent.tagName) ||parent.closest('[data-no-translate],svg,script,style,textarea,[contenteditable="true"],.user-passacarrers-list'))return false;return true;}
function translateNode(n){
  if(!nodeOk(n))return;
  const current=n.nodeValue||'';
  const previous=lastOutput.get(n);
  if(!originals.has(n)|| (previous!==undefined && current!==previous)) originals.set(n,current);
  const original=originals.get(n);
  const next=translate(original);
  if(next!==current)n.nodeValue=next;
  lastOutput.set(n,next);
}
function translateAttrs(el){
  if(el.closest('[data-no-translate],svg,[contenteditable="true"],.user-passacarrers-list'))return;
  for(const key of ['placeholder','aria-label','title']){
    if(!el.hasAttribute(key))continue;
    let obj=attrs.get(el);if(!obj){obj={};attrs.set(el,obj)}
    let last=lastAttrs.get(el);if(!last){last={};lastAttrs.set(el,last)}
    const current=el.getAttribute(key)||'';
    if(!Object.hasOwn(obj,key)|| (Object.hasOwn(last,key)&&current!==last[key]))obj[key]=current;
    const next=translate(obj[key]);
    if(current!==next)el.setAttribute(key,next);
    last[key]=next;
  }
}
function apply(root=document){
  if(!root)return;
  const doc=root.nodeType===9?root.documentElement:root;
  if(!doc)return;
  const walker=(doc.ownerDocument||document).createTreeWalker(doc,NodeFilter.SHOW_TEXT);
  let node;while((node=walker.nextNode()))translateNode(node);
  if(doc.nodeType===1)translateAttrs(doc);
  doc.querySelectorAll?.('[placeholder],[aria-label],[title]').forEach(translateAttrs);
  if(root===document){
    document.documentElement.lang=lang;
    translateGameFrame();
    document.querySelectorAll('[data-lang]').forEach(btn=>{
      const active=btn.dataset.lang===lang;btn.classList.toggle('is-active',active);btn.setAttribute('aria-pressed',active?'true':'false');
    });
  }
}
// Traducció de minijocs allotjats al mateix origen (iframe de l'APP).
const observedFrames=new WeakSet();
const gameFrame=document.querySelector('#gamePlayerFrame');
function translateGameFrame(){
  if(!gameFrame)return;
  try{
    const doc=gameFrame.contentDocument;
    if(!doc?.body)return;
    doc.documentElement.lang=lang;
    apply(doc);
    if(!observedFrames.has(doc)){
      const frameObserver=new MutationObserver(()=>requestAnimationFrame(()=>{
        try{if(gameFrame.contentDocument===doc)apply(doc)}catch(_){}
      }));
      frameObserver.observe(doc.body,{subtree:true,childList:true,characterData:true});
      observedFrames.add(doc);
    }
  }catch(_error){ /* Iframes externs no es modifiquen. */ }
}
gameFrame?.addEventListener('load',translateGameFrame);
let scheduled=false;
function schedule(){if(scheduled)return;scheduled=true;requestAnimationFrame(()=>{scheduled=false;apply()})}
const observer=new MutationObserver(records=>{
  if(records.some(x=>x.type==='childList'||x.type==='characterData'||(x.type==='attributes'&&['placeholder','aria-label','title'].includes(x.attributeName))))schedule();
});
